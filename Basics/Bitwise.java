public class Bitwise {
    public static void main(String[] args) {
        int a=5;
        int b=3;
        int pos=1;
        System.out.println(a&b);
        System.out.println(a|b);
        System.out.println(a^b);
        System.out.println(a<<pos);
        System.out.println(a>>pos);
    }
}
