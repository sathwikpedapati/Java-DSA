import java.util.*;
public class InOut {
    public static void main(String[] args) {
        Scanner input = new Scanner(System.in);
        // read integer
        int a= input.nextInt();
        // Printing the Input
        System.out.print(a);
        // Read the String
        String s = input.next();
        System.out.print(s);
        
    }
}