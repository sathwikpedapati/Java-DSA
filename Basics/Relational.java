public class Relational {
    public static void main(String[] args) {
        int a=5;
        int b=7;
        System.out.println(a>b); // a is greater than b
        System.out.println(a<b); // a is lesser than b
        System.out.println(a>=b); // a is greater than and equal to b
        System.out.println(a<=b); // a is lesser than and equal to b
        System.out.println(a==b); // a is equal to b
        System.out.println(a!=b); // a is not equal to b
    }
}
